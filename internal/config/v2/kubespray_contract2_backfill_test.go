// Legacy config: deployment.kubespray block without module sources must get
// the contract v2 pin backfilled at load, so a re-render resolves a module
// that accepts inventory_output_dir.
func TestNormalizeBackfillsKubesprayModuleSource(t *testing.T) {
	legacy := `---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
`
	cfg, err := DecodePublicConfig([]byte(legacy))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if cfg.Deployment.Kubespray == nil {
		t.Fatal("nil kubespray")
	}
	if !strings.Contains(cfg.Deployment.Kubespray.KubesprayCluster.Source, "2026.10.21-contract2") {
		t.Fatalf("kubespray_cluster source not backfilled: %q", cfg.Deployment.Kubespray.KubesprayCluster.Source)
	}
	if !strings.Contains(cfg.Deployment.Kubespray.Modules["kubespray"].Source, "2026.10.21-contract2") {
		t.Fatalf("modules.kubespray source not backfilled: %#v", cfg.Deployment.Kubespray.Modules)
	}
}

// Explicit user pin must survive untouched.
func TestNormalizeKeepsExplicitKubesprayModuleSource(t *testing.T) {
	cfg, err := DecodePublicConfig([]byte(`---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
    kubespray_cluster:
      source: github.com/example/fork.git//iac/provider/kubespray?ref=my-branch
      enabled: true
`))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if got := cfg.Deployment.Kubespray.KubesprayCluster.Source; got != "github.com/example/fork.git//iac/provider/kubespray?ref=my-branch" {
		t.Fatalf("explicit source overwritten: %q", got)
	}
}

// A config generated by an older CLI stamped the stale base release into the
// kubespray module slots. The loader must upgrade the stale gitops-base pin to
// the contract v2 ref (the CLI deploy path always renders in lifecycle mode,
// so a pre-contract-2 ref breaks kubespray-prepare), while a pin outside the
// gitops-base kubespray module path stays untouched.
func TestNormalizeUpgradesStaleKubesprayModulePin(t *testing.T) {
	cfg, err := DecodePublicConfig([]byte(`---
schema_version: "2.0"
opencenter:
  meta:
    name: argus
deployment:
  auto_deploy: true
  method: kubespray
  kubespray:
    version: 2.31.0
    kubespray_cluster:
      source: github.com/opencenter-cloud/openCenter-gitops-base.git//iac/provider/kubespray?ref=2026.03-rc2
      enabled: true
    modules:
      kubespray:
        source: github.com/example/fork.git//iac/provider/kubespray?ref=my-branch
        enabled: true
`))
	if err != nil {
		t.Fatal(err)
	}
	cl := NewConfigLoader(nil)
	if err := cl.normalize(cfg); err != nil {
		t.Fatal(err)
	}
	if got := cfg.Deployment.Kubespray.KubesprayCluster.Source; got != DefaultKubesprayModuleSourceURL {
		t.Fatalf("stale gitops-base pin not upgraded: %q", got)
	}
	if got := cfg.Deployment.Kubespray.Modules["kubespray"].Source; got != "github.com/example/fork.git//iac/provider/kubespray?ref=my-branch" {
		t.Fatalf("fork pin overwritten: %q", got)
	}
	if RequiresKubesprayModuleContract2Upgrade(cfg) {
		t.Fatal("upgraded config still flagged for upgrade")
	}
}

// The generation gate must block a config whose module slots still pin a
// pre-contract-2 gitops-base ref, naming the contract and the repair command.
func TestValidateGenerationBlocksStaleKubesprayModulePin(t *testing.T) {
	cfg, err := NewV2Default("stale-gate", "openstack")
	if err != nil {
		t.Fatal(err)
	}
	module := cfg.Deployment.Kubespray.Modules["kubespray"]
	module.Source = "github.com/opencenter-cloud/openCenter-gitops-base.git//iac/provider/kubespray?ref=2026.03-rc2"
	cfg.Deployment.Kubespray.Modules["kubespray"] = module

	report := ValidateGeneration(cfg)
	var found bool
	for _, issue := range report.Issues {
		if issue.Path == "deployment.kubespray" &&
			strings.Contains(issue.Message, "lifecycle contract 2") &&
			strings.Contains(issue.Message, "opencenter cluster set") {
			found = true
		}
	}
	if !found {
		t.Fatalf("stale kubespray pin not reported: %+v", report.Issues)
	}
	if report.Valid {
		t.Fatal("stale kubespray pin must invalidate the report")
	}
}
